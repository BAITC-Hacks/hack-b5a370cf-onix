export function makeT(lang: Lang) {
  const dict = ui[lang];
  const t = (key: UIKey, params: Record<string, string | number> = {}) =>
    String(dict[key]).replace(/\{(\w+)\}/g, (_, p) => String(params[p] ?? `{${p}}`));

  const district = (id?: string | null, scope: "city" | "district" = "city") => {
    if (!id) return scope === "district" ? (lang === "kz" ? "аудан таңдалмаған" : "район не выбран") : dict.wholeCity;
    return lang === "kz" ? districtKz[id]?.name ?? id : DISTRICTS.find((d) => d.id === id)?.name ?? id;
  };
  /** Название района по русскому имени (результаты движка содержат имя). */
  const districtByName = (name: string) => {
    if (name === "весь город") return dict.wholeCity;
    const d = DISTRICTS.find((x) => x.name === name);
    return d ? district(d.id) : name;
  };
  const profile = (id: string) => (lang === "kz" ? districtKz[id]?.profile : DISTRICTS.find((d) => d.id === id)?.profile) ?? "";
  const indicator = (k: Indicator) => (lang === "kz" ? indicatorKz[k] : INDICATOR_INFO[k].name);
  const direction = (d: Direction) => (lang === "kz" ? directionKz[d] : DIRECTION_LABELS[d]);
  const measure = (id: string) => (lang === "kz" ? measureKz[id] : MEASURES.find((m) => m.id === id)?.name) ?? id;
  const event = (id: string) => {
    const e = EVENTS.find((x) => x.id === id)!;
    return lang === "kz" ? eventKz[id] : { title: e.title, description: e.description };
  };

  const issue = (i: Issue): string => {
    const ru = lang === "ru";
    switch (i.code) {
      case "unknown":
        return ru ? `Неизвестное мероприятие ${i.measureId}` : `Белгісіз шара ${i.measureId}`;
      case "needDistrict":
        return ru ? `${i.measureId}: выберите район` : `${i.measureId}: ауданды таңдаңыз`;
      case "badDistrict":
        return ru ? `${i.measureId}: неизвестный район` : `${i.measureId}: белгісіз аудан`;
      case "cityNoDistrict":
        return ru ? `${i.measureId} — городская мера` : `${i.measureId} — қалалық шара`;
      case "count":
        return ru ? `Нужно ровно ${i.limit} решений, выбрано ${i.n}` : `Дәл ${i.limit} шешім керек, таңдалғаны ${i.n}`;
      case "duplicate":
        return ru ? `${i.measureId} уже в плане` : `${i.measureId} жоспарда бар`;
      case "budget":
        return ru ? `Бюджет превышен: ${i.n} из ${i.limit}` : `Бюджет асып кетті: ${i.limit}-тан ${i.n}`;
      case "direction":
        return ru
          ? `«${direction(i.direction!)}»: не более ${i.limit} мер`
          : `«${direction(i.direction!)}»: ${i.limit} шарадан аспайды`;
      case "conflict":
        return ru ? `${i.measureId} и ${i.otherId} несовместимы (BRT или ЛРТ)` : `${i.measureId} және ${i.otherId} үйлесімсіз (BRT не ЛРТ)`;
      case "conflictSame":
        return ru
          ? `${i.measureId} и ${i.otherId} нельзя в одном районе (${district(i.districtId)})`
          : `${i.measureId} және ${i.otherId} бір ауданда болмайды (${district(i.districtId)})`;
    }
  };

  return { t, lang, suggestions: dict.suggestions, district, districtByName, profile, indicator, direction, measure, event, issue };
}

export type Translator = ReturnType<typeof makeT>;
